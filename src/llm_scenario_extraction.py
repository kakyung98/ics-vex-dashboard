def digest(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,ensure_ascii=False).encode()).hexdigest()


def obj(properties):
    return dict(type='object',properties=properties,required=list(properties),additionalProperties=False)


def schema(packet):
    string={'type':'string'};nullable={'type':['string','null']}
    evidence=obj(dict(source_id={'enum':[s['id'] for s in packet['sources']]},quote={'type':'string','minLength':1},occurrence={'type':'integer','minimum':0,'description':'Zero-based quote occurrence. First occurrence is 0.'}))
    condition=obj(dict(id=string,statement=string,relation={'enum':['necessary_for_described_path','unresolved_candidate']},
        operator_observable={'type':'boolean'},question=nullable,evidence_request=nullable,evidence=evidence))
    fact=obj(dict(role={'enum':['action','impact','trigger','mitigation','applicability','explicit_nonrequirement','observed_context']},statement=string,evidence=evidence))
    scenario=obj(dict(id=string,scope_id={'enum':[s['id'] for s in packet['scopes']]},path_description=string,
        path_evidence=evidence,conditions={'type':'array','items':condition},
        logic_nodes={'type':'array','items':obj(dict(id=string,op={'enum':['and','or','not','unknown']},inputs={'type':'array','items':string},evidence=evidence))},
        logic_root=nullable,unknowns={'type':'array','items':string}))
    return obj(dict(packet_id={'const':packet['packet_id']},cve={'const':packet['cve']},
        scenarios={'type':'array','items':scenario},other_facts={'type':'array','items':fact},unknowns={'type':'array','items':string}))


def validate(packet,value):
    from jsonschema import Draft7Validator
    Draft7Validator(schema(packet)).validate(value)
    if packet.get('identity_status')=='Rejected' and value['scenarios']:raise ValueError('Rejected CVE identity cannot receive scenarios')
    sources={s['id']:s for s in packet['sources']};references=[]
    def ref(evidence,scope=None):
        source=sources[evidence['source_id']]
        if source.get('subject_ambiguous'):raise ValueError('Ambiguous CVE subject needs source-scope review')
        if scope is not None and source['scope_id']!=scope:raise ValueError('Cross-product/source scope')
        quote=evidence['quote'];start=-1
        for _ in range(evidence['occurrence']+1):
            start=source['text'].find(quote,start+1)
            if start<0:raise ValueError('Quotation not found at stated occurrence')
        references.append(dict(**evidence,span=[start,start+len(quote)],source_sha256=source['text_sha256']))
    ids=set()
    for scenario in value['scenarios']:
        if scenario['id'] in ids:raise ValueError('Duplicate scenario ID')
        ids.add(scenario['id']);scope=scenario['scope_id'];ref(scenario['path_evidence'],scope)
        nodes={};condition_ids=set()
        for c in scenario['conditions']:
            if c['id'] in nodes:raise ValueError('Duplicate condition ID')
            nodes[c['id']]=set();condition_ids.add(c['id']);ref(c['evidence'],scope)
            if c['operator_observable']:
                if not c['question'] or not c['evidence_request']:raise ValueError('Observable condition needs a question and evidence request')
            elif c['question'] is not None or c['evidence_request'] is not None:raise ValueError('Unobservable condition cannot become an operator question')
        for n in scenario['logic_nodes']:
            if n['id'] in nodes:raise ValueError('Duplicate logic node ID')
            if not n['inputs'] or not set(n['inputs'])<=set(nodes):raise ValueError('Logic has forward/unknown references')
            if n['op']=='not' and len(n['inputs'])!=1:raise ValueError('NOT needs exactly one input')
            nodes[n['id']]=set().union(*(nodes[i]|({i} if i in condition_ids else set()) for i in n['inputs']))
            ref(n['evidence'],scope)
        root=scenario['logic_root']
        if condition_ids:
            if root not in nodes:raise ValueError('Missing logic root')
            used=nodes[root]|({root} if root in condition_ids else set())
            if used!=condition_ids:raise ValueError('Logic omits extracted conditions')
        elif root is not None or scenario['logic_nodes']:raise ValueError('Empty conditions cannot have a Boolean formula')
    for fact in value['other_facts']:ref(fact['evidence'])
    return dict(exact_references=references,mechanical_checks_passed=True,semantic_accuracy_verified=False,
        source_meaning_review='pending',native_export_ready=False,vex_eligible=False)


def native_drafts(packet,value):
    """Identity/provenance-only native projection; unknown native fields stay absent.

    LLM conditions/logic/questions are a separate project extension. Textual
    action/impact candidates require field-local semantic mapping before export.
    """
    sources={s['id']:s for s in packet['sources']};scopes={s['id']:s for s in packet['scopes']}
    drafts=[]
    for scenario in value['scenarios']:
        native={'id':str(uuid.uuid5(uuid.NAMESPACE_URL,packet['packet_id']+':'+scenario['id'])),
            'evidencedBySource':[sources[scenario['path_evidence']['source_id']]['url']]}
        scope=scopes[scenario['scope_id']]
        if scope.get('member_count')==1 and len(scope.get('product_names',[]))==1:
            native['affectsProduct']={'hasProductEnumeration':[{'scheme':'urn:ics-vex:source-product-text','values':scope['product_names']}]}
        drafts.append({'native_draft':{'Vulnerability':{'hasIdentity':[{'scheme':'https://www.cve.org/','value':packet['cve']}],'hasScenario':[native]}},
            'project_extension':scenario,'action_impact_text_candidates':value['other_facts'],
            'native_export_ready':False,'human_semantic_review':'pending',
            'blockers':['Required native action/impact/context/role/scope/criticality and originating-product fields have not been source-reviewed.',
                'Product-set membership does not establish universal applicability of extracted prerequisites.']})
    return drafts
