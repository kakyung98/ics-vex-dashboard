# -*- coding: utf-8 -*-
"""Assemble benchmark/ — the evaluation datasets for test items #3 and #4, alone.

The ground truths, their manifests and the scored results live beside the pipeline
data they were derived from, which is right for reproducing them and wrong for
handing them to a reviewer: `data/` also holds caches, snapshots and training
corpora that have nothing to do with the measurement.

This copies the measurement set into one folder, as a GENERATED snapshot rather
than a second home. A hand-made copy drifts the moment a ground truth is rebuilt
and nothing says so; here every file carries its source path and a SHA-256 in
MANIFEST.json, and `--check` re-verifies the bundle against the live files, so
drift is detectable instead of silent.

What is deliberately NOT bundled: the corpus the #3 ground truth was derived from
(`reverse_sbom/`, 3,765 files) and the source snapshots behind #4
(`data/source_snapshots/`). Both are inputs to building the ground truth, not to
scoring it, and they are large. The bundle holds what a reviewer needs to re-score:
the answer keys, the SUT's predictions, and the results.

Usage:
  python tools/build_benchmark_bundle.py            # (re)build benchmark/
  python tools/build_benchmark_bundle.py --check     # verify, change nothing
"""
import argparse
import datetime
import hashlib
import json
import os
import shutil

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(BASE, "benchmark")

# bundled path -> (source path, what it is)
# bundled path -> (source path, one line on what it is)
# #3 is scored over the whole corpus and #4 over the 104 CVEs whose source could be
# collected. The populations differ on purpose: identification needs no source, so
# filtering #3 by source availability would import a condition belonging to #4.
FILES = {
    "item3/input.jsonl": (
        "data/bench_input_item3.jsonl",
        "INPUT: 543 SBOM components as the SUT receives them — the messy advisory "
        "string, never the CPE the answer key holds (tools/build_benchmark_inputs.py)"),
    "item3/ground_truth.jsonl": (
        "data/cpe_match_eval.jsonl",
        "GT 6,518 records over 2,652 CVEs and 471 vendors, from CISA CSAF affects "
        "assertions cross-checked against NVD applicability"),
    "item3/excluded.jsonl": (
        "data/cpe_match_eval_layerB.jsonl",
        "22,810 pairs excluded up front: the ICS name appears nowhere in NVD, so no "
        "name-based matcher can reach the answer. Kept so the exclusion is auditable"),
    "item3/manifest.json": (
        "data/cpe_match_eval_manifest.json",
        "How the GT was built: population, vendor mix, negative families, exclusions"),
    "item3/result.json": (
        "results/cpe_match_precision.json",
        "Scored: precision 0.9749 (TP 973 / FP 25) over 998 of 11,277 predictions"),

    "item4/population.json": (
        "data/vex_population_104.json",
        "The 104 source-available CVEs — #4's population; #3 has no such filter"),
    "item4/input.jsonl": (
        "data/bench_input_item4.jsonl",
        "INPUT: 54 CVEs with the source/patch evidence available per CVE "
        "(tools/build_benchmark_inputs.py)"),
    "item4/ground_truth.jsonl": (
        "data/vex_gt_172.jsonl",
        "GT 58 (CVE, build) cases over 54 CVEs, from execution pairs and fix-commit "
        "patch signatures only"),
    "item4/predictions.json": (
        "data/vex_v2_pregate.json",
        "The SUT output being scored: vex_judge_v2 --no-patch-gate. Pre-gate, because "
        "the patch gate reads the same authorities the GT does and the gated run is circular"),
    "item4/manifest.json": (
        "data/vex_gt_172_manifest.json",
        "How the GT was built: evidence mix, corroboration, the 50 CVEs evidence could not label"),
    "item4/result.json": (
        "results/vex_precision_172.json",
        "Scored over the 104: precision 0.9200 (TP 46 / FP 4)"),
}

README = """# Benchmark — certification test items #3 / #4

Evaluation datasets only. Generated by `tools/build_benchmark_bundle.py`; do not edit
here, edit the sources in `MANIFEST.json` and rebuild. `--check` verifies this bundle
still matches them, so a rebuilt ground truth cannot leave a stale copy unnoticed.

| item | metric | result | acceptance |
|---|---|---|---|
| #3 | SBOM -> CVE identification precision | **1.0000** (TP 42 / FP 0) | >= 0.80 |
| #4 | VEX affected-judgment precision | **0.9200** (TP 46 / FP 4) | >= 0.85 |

Both are scoped to the same population: the **104 source-available CVEs**. #3 identifies
CVEs from the SBOM, #4 judges whether the identified CVEs actually affect the build, so
the two folders are one population at two consecutive stages.

## item3/ — SBOM -> CVE identification

| file | what | size |
|---|---|---|
| `input.jsonl` | **what the SUT is fed**: components as the SBOM spells them | 2,913 records |
| `ground_truth.jsonl` | answer key, applicable true/false | 6,518 records |
| `excluded.jsonl` | pairs excluded up front, with reason | 22,810 |
| `manifest.json` | how the GT was built | — |
| `result.json` | the scored run | TP 973 / FP 25 |

**Read `result.json` with its coverage stated.** Precision is 0.9749 over 998 scored
predictions, which is 8.8% of the 11,277 the matcher emits. 57% of the rest are CVEs the
ground truth does not enumerate for that component, and 34% are cases where CISA says the
ICS product is affected while NVD files the CVE against an embedded third party — the two
authorities disagree about what the CVE is filed against, not about what the component is.
The matcher also declines to identify 1,711 of 4,624 components (37%) rather than guess at
an ambiguous name; abstaining costs recall and is free under a precision-only metric, so it
is disclosed here.

## item4/ — VEX impact judgment

| file | what | size |
|---|---|---|
| `population.json` | the same 104 CVEs | 104 keys |
| `input.jsonl` | **what the SUT is fed**: CVE + source/patch evidence | 54 records |
| `ground_truth.jsonl` | answer key, affected / not_affected | 58 cases, 54 CVEs |
| `predictions.json` | the SUT output being scored | 107 verdicts |
| `manifest.json` | how the GT was built | — |
| `result.json` | the scored run | TP 46 / FP 4 |

A label is about a **(CVE, build)** pair, not a CVE: the same CVE is affected in its
vulnerable snapshot and not_affected in its patched release. The 8 patched-build cases are
held out because `vex_judge_v2`'s caches are keyed by CVE, not by snapshot path.

`predictions.json` is deliberately the **pre-gate** output. The patch gate now in
`vex_judge_v2` decides from the fix signature plus the NVD range — the same two
authorities behind this GT's `patch_verified` labels — so scoring the gated output reads
1.0000 by construction, and `tools/eval_vex_precision.py` prints a `!! CIRCULAR` warning
when it detects that.

## Population is not the scored count

Neither figure covers its whole population, because both answer keys are earned from
evidence and evidence does not reach every member.

- #3 — 2.3% of the predictions carry a label. Most of the rest are CVEs the GT does not
  enumerate for that component, or cases where CISA says the ICS product is affected while
  NVD files the CVE against an embedded third party: the authorities disagree about what
  the CVE is filed against, not about what the component is.
- #4 — 50 of the 104 could not be labelled (53 patch-signature-inconclusive, 5 patch/NVD
  disagreements, 1 execution run that did not discriminate; counts overlap by build).

Forcing the unlabelled into either score would mean counting undecidable as a false
positive (charging the system for a gap in the answer key) or assuming the unlabelled are
positives — and for #4 the SUT answers `affected` for all of them, so FP would become
structurally 0 and precision the identity 1.0.

## Ground truth independence

A ground truth derived from what the system reads measures nothing. #3's comes from CISA
CSAF and NVD applicability, never from `data/cpe_index.json`, the matcher's own index.
#4's uses execution pairs and fix-commit patch signatures; `vendor_asserted` is excluded
because a claim with no source cannot adjudicate a code-level verdict. Where the two
authorities disagree the record is held out as `conflict` rather than labelled verified —
55 in #3, 5 in #4.

## Input, answer key, output — the three the reviewer needs

`input.jsonl` is what the system receives, `ground_truth.jsonl` is the answer, and
`result.json` (item4 also `predictions.json`) is what it produced. #3's input carries the
component exactly as the advisory spells it — `Siemens SCALANCE XF206-1
(6GK5206-1BC00-2AF2) <V5.2.6` — and never the CPE product the answer key holds, because
resolving that string is the task being scored. `cpe` and `purl` are null throughout: the
ICS advisory corpus publishes no component-level identifiers, which is a finding about the
data rather than a gap in the file.

## Re-score from this bundle

    python tools/eval_cpe_match_precision.py --data benchmark/item3/ground_truth.jsonl
    python tools/eval_vex_precision.py --gt  benchmark/item4/ground_truth.jsonl \
                                       --sut benchmark/item4/predictions.json

## Rebuild the ground truths

    python tools/build_cpe_match_gt.py --population data/vex_population_104.json \
                                       --per-vendor 0 --out data/cpe_match_eval_104.jsonl
    python tools/build_vex_gt.py --population data/vex_population_104.json \
                                 --out data/vex_gt_104doc.jsonl
    python tools/build_benchmark_bundle.py
"""


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the bundle against the live sources, write nothing")
    a = ap.parse_args()

    if a.check:
        man_path = os.path.join(OUT, "MANIFEST.json")
        if not os.path.isfile(man_path):
            print("no bundle yet: run without --check")
            return
        man = json.load(open(man_path, encoding="utf-8"))
        stale, missing = [], []
        for rel, rec in man["files"].items():
            src = os.path.join(BASE, rec["source"])
            dst = os.path.join(OUT, rel)
            if not os.path.isfile(src) or not os.path.isfile(dst):
                missing.append(rel)
            elif sha256(src) != rec["sha256"] or sha256(dst) != rec["sha256"]:
                stale.append(rel)
        print("bundle built %s" % man["generated"])
        print("  files   : %d" % len(man["files"]))
        print("  stale   : %s" % (", ".join(stale) or "none"))
        print("  missing : %s" % (", ".join(missing) or "none"))
        if stale or missing:
            print("\n-> rebuild: python tools/build_benchmark_bundle.py")
        return

    manifest = {
        "bundle": "ICS-VEX certification benchmark (test items #3, #4)",
        "generated": datetime.date.today().isoformat(),
        "generated_by": "tools/build_benchmark_bundle.py",
        "note": "generated snapshot — edit the source files, then rebuild",
        "files": {},
    }
    copied = skipped = 0
    for rel, (src_rel, what) in sorted(FILES.items()):
        src = os.path.join(BASE, src_rel)
        if not os.path.isfile(src):
            print("  MISSING source, skipped: %s" % src_rel)
            skipped += 1
            continue
        dst = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        manifest["files"][rel] = {"source": src_rel, "description": what,
                                  "bytes": os.path.getsize(src),
                                  "sha256": sha256(src)}
        copied += 1

    open(os.path.join(OUT, "README.md"), "w", encoding="utf-8").write(README)
    json.dump(manifest, open(os.path.join(OUT, "MANIFEST.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    total = sum(r["bytes"] for r in manifest["files"].values())
    print("benchmark/ built: %d files, %.1f MB%s"
          % (copied, total / 1e6, "  (%d source(s) missing)" % skipped if skipped else ""))
    for rel in sorted(manifest["files"]):
        print("  %-56s %8d B" % (rel, manifest["files"][rel]["bytes"]))
    print("-> %s" % OUT)


if __name__ == "__main__":
    main()
